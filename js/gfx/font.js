  function width(text, scale) {
    scale = scale || 1;
    return String(text).length * (W + GAP) * scale - GAP * scale;
  }

  function draw(ctx, text, x, y, color, scale) {
    scale = scale || 1;
    color = color || '#e8e8d0';
    ctx.fillStyle = color;
    let cx = x;
    for (const raw of String(text)) {
      const ch = G[raw] ? raw : raw.toUpperCase();
      const rows = G[ch];
      if (rows) {
        for (let r = 0; r < H; r++) {
          const bits = rows[r];
          for (let c = 0; c < W; c++) {
            if (bits & (0x10 >> c)) {
              ctx.fillRect(cx + c * scale, y + r * scale, scale, scale);
            }
          }
        }
      }
      cx += (W + GAP) * scale;
    }
  }

  /* centered horizontally at given point */
  function drawCentered(ctx, text, cx, y, color, scale) {
    const w = width(text, scale);
    draw(ctx, text, Math.round(cx - w / 2), y, color, scale);
  }

  return { draw, drawCentered, width, G, W, H, GAP };
